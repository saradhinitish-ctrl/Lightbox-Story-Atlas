// Builds lightbox.css, the one stylesheet the app loads, from the partials in css/.
//
//   node tools/build-css.mjs          write lightbox.css and stamp its version into index.html
//   node tools/build-css.mjs --check  fail if lightbox.css is out of date (use before committing)
//
// No dependencies. The order below IS the cascade: a later file wins over an earlier one at equal
// specificity, and unlayered rules beat the Tailwind layers in framework.css. Keep it stable.
//
// first-page.css, first-page.js and widget-entry.js are NOT bundled: the native Android app swaps in its own
// edition of those three files by exact path (StudioLauncherActivity.shouldInterceptRequest), so the web
// must keep requesting them separately at the root.
import {readFile, writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {resolve} from 'node:path';
import process from 'node:process';

const root = resolve(import.meta.dirname, '..');

// Two bundles, because first-page.css sits between them in the cascade and has to stay a separate request.
export const BUNDLES = {
  'lightbox.css': [
    'fonts',               // @font-face for every family; one file per script subset
    'framework',           // Tailwind output for the React app (layered: theme, base, components, utilities)
    'mobile-refinements',
    'screenplay-polish',
    'install-app',
    'studio-design',       // Acid Paper: the studio's palette, type and chrome
    'opening',
  ],
  // ...first-page.css loads here...
  'lightbox-app.css': [
    'story-cylinder-v9',   // the Atlas line: prints, pegs and the darkroom
    'material-design',
    'light-table-surfaces',
    'light-table',
    'light-table-atlas',
    'beat-table',
    'writing-rooms',
    'atlas-light-table',
    'light-table-rooms',
    'field-kit',           // phone-only layer (max-width: 767px); must stay late
    'title-sequence',
  ],
};

export async function build(file) {
  let out = `/* Lightbox: generated by tools/build-css.mjs from css/*.css. Edit the partials, not this file. */\n`;
  for (const name of BUNDLES[file]) {
    const text = await readFile(resolve(root, 'css', name + '.css'), 'utf8');
    // Partials live in css/ and write file URLs relative to there (../assets/..., ../app-icons/...); the bundles sit at the root.
    out += `\n/* ===== ${name}.css ===== */\n${text.trimEnd().replace(/url\((["']?)\.\.\/(?!\.)/g, 'url($1./')}\n`;
  }
  return out;
}

if (import.meta.main ?? process.argv[1] === import.meta.filename) {
  const check = process.argv.includes('--check');
  const html = resolve(root, 'index.html');
  let page = await readFile(html, 'utf8');
  let failed = false;
  for (const file of Object.keys(BUNDLES)) {
    const css = await build(file);
    const hash = createHash('sha1').update(css).digest('hex').slice(0, 8);
    const target = resolve(root, file);
    if (check) {
      const current = await readFile(target, 'utf8').catch(() => '');
      if (current !== css) { console.error(file + ' is out of date. Run: node tools/build-css.mjs'); failed = true; }
      else console.log(file + ' is up to date (' + hash + ')');
    } else {
      await writeFile(target, css);
      page = page.replace(new RegExp(`(href="\\./${file.replace('.', '\\.')})(\\?v=[0-9a-f]+)?"`), `$1?v=${hash}"`);
      console.log(`${file} ${(css.length / 1024).toFixed(0)} KB, version ${hash}`);
    }
  }
  if (check) process.exit(failed ? 1 : 0);
  await writeFile(html, page);
}
